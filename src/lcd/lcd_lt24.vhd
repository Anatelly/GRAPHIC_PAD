library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- ============================================================
-- Модуль cmd2lcd
-- Назначение:
--   Управление записью команд и данных в LCD-дисплей
--   через 16-битную параллельную шину.
--
-- Особенности:
--   * Запись команд LCD;
--   * Запись данных (например, пикселей изображения);
--   * Формирование сигналов CS_N, RS, WR_N;
--   * Поддержка нескольких слов данных для одной команды;
--   * Чтение из LCD отключено: RD_N постоянно равен '1'.
--
-- Touchpad в этом модуле не используется.
-- ============================================================

entity lcd_lt24 is

    -- --------------------------------------------------------
    -- Параметры длительности сигналов записи.
    -- Эти значения задаются в тактах clk.
    -- --------------------------------------------------------
    generic (
        W_HIGH_END : natural := 2;
        -- Количество тактов для фазы высокого уровня счетчика.
        -- Используется для определения момента завершения записи.

        W_LOW_END  : natural := 2
        -- Предел счетчика низкой фазы.
        -- Определяет длительность этапа формирования WR_N.
    );

    port (

        -- ----------------------------------------------------
        -- Синхронизация и сброс
        -- ----------------------------------------------------
        clk   : in std_logic;
        -- Тактовый сигнал модуля.
        -- Все основные процессы работают по его переднему фронту.

        rst_n : in std_logic;
        -- Асинхронный сброс с активным низким уровнем.
        -- rst_n = '0' переводит модуль в начальное состояние.

        -- ----------------------------------------------------
        -- Вход команды
        -- ----------------------------------------------------
        cmd_valid : in std_logic;
        -- '1' означает, что на входе cmd находится
        -- действительная команда для отправки в LCD.

        cmd : in std_logic_vector(7 downto 0);
        -- Код команды LCD, например:
        -- x"2A" — установка диапазона координат X;
        -- x"2B" — установка диапазона координат Y;
        -- x"2C" — начало записи пикселей в память дисплея.
        -- Конкретное назначение зависит от контроллера LCD.

        cmd_cycle : in std_logic_vector(15 downto 0);
        -- Количество циклов записи данных, относящихся
        -- к текущей команде.
        -- В этой реализации значение сравнивается
        -- со счетчиком cycle_cnt.

        -- ----------------------------------------------------
        -- Вход слова данных
        -- ----------------------------------------------------
        data_wr_valid : in std_logic;
        -- '1' означает, что на входе data_wr есть
        -- действительное слово данных для отправки.

        data_wr : in std_logic_vector(15 downto 0);
        -- 16-битное слово данных.
        -- Например, один пиксель в формате RGB565.

        -- ----------------------------------------------------
        -- Сигналы подтверждения и завершения
        -- ----------------------------------------------------
        ack_wr : out std_logic;
        -- Подтверждение этапа передачи слова данных.
        -- Формируется при выполнении условия записи.

        cmd_finish : out std_logic;
        -- '1' означает, что автомат завершил обработку
        -- текущей команды и перешел в C2L_FINISH.

        wrphase_finish : out std_logic;
        -- Признак завершения фазы записи данных.
        -- Используется как сигнал состояния процесса записи.

        -- ----------------------------------------------------
        -- Управляющие сигналы LCD
        -- ----------------------------------------------------
        csn : out std_logic;
        -- Chip Select, активный низким уровнем.
        -- '0' — LCD выбран для обмена данными.

        data_cmdn : out std_logic;
        -- Выбор типа передаваемой информации.
        -- '0' — передается команда;
        -- '1' — передаются данные.
        -- Обычно соответствует сигналу D/C или RS дисплея.

        wrn : out std_logic;
        -- Write Strobe, активный низким уровнем.
        -- Низкий уровень обозначает активную фазу записи.

        rdn : out std_logic;
        -- Read Strobe, активный низким уровнем.
        -- Чтение из дисплея не используется, поэтому сигнал
        -- постоянно удерживается в неактивном состоянии ('1').

        -- ----------------------------------------------------
        -- Двунаправленная шина LCD
        -- ----------------------------------------------------
        data_lcd : inout std_logic_vector(15 downto 0)
        -- 16-битная шина данных дисплея.
        -- Во время записи модуль управляет шиной.
        -- В режиме отключенного выходного драйвера шина
        -- переводится в высокоимпедансное состояние 'Z'.
    );
end entity lcd_lt24;


architecture rtl of lcd_lt24 is

    -- ========================================================
    -- 1. Состояния конечного автомата
    -- ========================================================

    type state_type is (
        C2L_IDLE,
        -- Ожидание новой команды.

        C2L_CMD_PH,
        -- Фаза отправки команды LCD.

        C2L_WAIT_VALID,
        -- Ожидание данных после отправки команды.

        C2L_WRITE_DATA,
        -- Фаза отправки слова данных.

        C2L_WAIT_WR_VALID,
        -- Ожидание следующей команды или слова данных
        -- после завершения текущей записи.

        C2L_FINISH
        -- Завершение обработки команды.
    );

    signal state : state_type := C2L_IDLE;
    -- Текущее состояние автомата.
    -- По нему определяется, что должен делать модуль
    -- в данный момент.

    signal next_state : state_type := C2L_IDLE;
    -- Следующее состояние автомата.
    -- Вычисляется на основании текущего состояния
    -- и входных сигналов.


    -- ========================================================
    -- 2. Счетчики временных интервалов
    -- ========================================================

    signal high_cnt : unsigned(7 downto 0) := (others => '0');
    -- Счетчик длительности фазы записи.
    -- Увеличивается при достижении предела low_cnt.
    -- Когда high_cnt достигает W_HIGH_END, запись
    -- считается завершенной.

    signal low_cnt : unsigned(7 downto 0) := (others => '0');
    -- Счетчик короткого временного интервала внутри
    -- фазы записи.
    -- Используется для управления моментом изменения WR_N.

    signal cycle_cnt : unsigned(15 downto 0) := (others => '0');
    -- Счетчик завершенных циклов передачи.
    -- Увеличивается при завершении отправки команды
    -- или слова данных.
    -- Сравнивается со значением cmd_cycle.


    -- ========================================================
    -- 3. Внутренние сигналы завершения и управления шиной
    -- ========================================================

    signal write_finish : std_logic := '0';
    -- Внутренний признак окончания текущей фазы записи.
    -- Формируется, когда автомат находится в CMD_PH
    -- или WRITE_DATA и high_cnt достигает W_HIGH_END.

    signal data_lcd_oe : std_logic := '0';
    -- Output Enable — разрешение управления шиной data_lcd.
    -- '1' — модуль выводит значение на шину.
    -- '0' — модуль освобождает шину, устанавливая 'Z'.

    signal data_lcd_out : std_logic_vector(15 downto 0)
                          := (others => '0');
    -- Значение, которое будет выведено на data_lcd.
    -- Для команды старшие 8 бит равны нулю,
    -- младшие 8 бит содержат cmd.
    -- Для данных используется полное 16-битное слово data_wr.

begin

    -- ========================================================
    -- 4. Подключение внутреннего регистра к внешней шине
    -- ========================================================

    data_lcd <= data_lcd_out when data_lcd_oe = '1' else 
                (others => 'Z');
    -- Если data_lcd_oe = '1', шина управляется модулем.
    -- Если data_lcd_oe = '0', выводы переходят в Z-состояние.
    --
    -- Важно: поддержка двунаправленной шины и внутренних
    -- тристейт-драйверов зависит от FPGA и способа подключения.
    -- При необходимости тристейт следует реализовать на верхнем
    -- уровне проекта.

    rdn <= '1';
    -- Чтение отключено: RD_N всегда неактивен.


    -- ========================================================
    -- 5. Формирование write_finish
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            -- При сбросе запись не завершена.
            write_finish <= '0';

        elsif rising_edge(clk) then

            -- Завершение фазы записи команды или данных.
            if ((state = C2L_CMD_PH) or
                (state = C2L_WRITE_DATA)) and
               (high_cnt = to_unsigned(W_HIGH_END, high_cnt'length))
            then
                write_finish <= '1';
            else
                write_finish <= '0';
            end if;

        end if;
    end process;


    -- ========================================================
    -- 6. Счетчик high_cnt
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            high_cnt <= (others => '0');

        elsif rising_edge(clk) then

            -- После завершения записи начинаем новый отсчет.
            if write_finish = '1' then
                high_cnt <= (others => '0');

            -- Счетчик работает только во время передачи
            -- команды или слова данных.
            elsif (state = C2L_CMD_PH) or
                  (state = C2L_WRITE_DATA) then

                -- Увеличиваем high_cnt на единицу,
                -- когда low_cnt достиг заданного предела.
                if low_cnt = to_unsigned(W_LOW_END, low_cnt'length) then
                    high_cnt <= high_cnt + 1;
                end if;

            else
                -- В остальных состояниях счетчик сброшен.
                high_cnt <= (others => '0');
            end if;

        end if;
    end process;


    -- ========================================================
    -- 7. Счетчик low_cnt
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            low_cnt <= (others => '0');

        elsif rising_edge(clk) then

            -- Начинаем счет, когда в состоянии ожидания
            -- обнаружена новая команда.
            if (state = C2L_IDLE) and (cmd_valid = '1') then
                low_cnt <= to_unsigned(1, low_cnt'length);

            -- Во время передачи команды или данных
            -- отсчитываем короткий временной интервал.
            elsif (state = C2L_CMD_PH) or
                  (state = C2L_WRITE_DATA) then

                -- Если достигнут предел, начинаем отсчет заново.
                if low_cnt = to_unsigned(W_LOW_END, low_cnt'length) then
                    low_cnt <= to_unsigned(1, low_cnt'length);
                else
                    low_cnt <= low_cnt + 1;
                end if;

            -- По завершении фазы записи счетчик обнуляется.
            elsif write_finish = '1' then
                low_cnt <= (others => '0');
            end if;

        end if;
    end process;


    -- ========================================================
    -- 8. Счетчик cycle_cnt
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            cycle_cnt <= (others => '0');

        elsif rising_edge(clk) then

            -- В начале новой команды начинаем подсчет сначала.
            if state = C2L_IDLE then
                cycle_cnt <= (others => '0');

            -- Если в состоянии ожидания следующего слова
            -- появилась новая команда, счетчик также сбрасывается.
            elsif (state = C2L_WAIT_WR_VALID) and
                  (cmd_valid = '1') then
                cycle_cnt <= (others => '0');

            -- Завершение передачи команды увеличивает счетчик.
            elsif (state = C2L_CMD_PH) and
                  (write_finish = '1') then

                if cycle_cnt /= x"FFFF" then
                    cycle_cnt <= cycle_cnt + 1;
                end if;

            -- Завершение передачи слова данных увеличивает счетчик.
            elsif (state = C2L_WRITE_DATA) and
                  (write_finish = '1') then

                if cycle_cnt /= x"FFFF" then
                    cycle_cnt <= cycle_cnt + 1;
                end if;
            end if;

        end if;
    end process;


    -- ========================================================
    -- 9. Комбинационная логика конечного автомата
    -- ========================================================

    process(state, cmd_valid, cmd_cycle, data_wr_valid, cycle_cnt,
            write_finish)
    begin

        -- По умолчанию сохраняем текущее состояние.
        -- Если ни одно условие перехода не сработает,
        -- автомат останется на месте.
        next_state <= state;

        case state is

            -- ------------------------------------------------
            -- C2L_IDLE: ожидание команды
            -- ------------------------------------------------
            when C2L_IDLE =>

                if cmd_valid = '1' then
                    -- Получена команда — начинаем ее передачу.
                    next_state <= C2L_CMD_PH;
                end if;


            -- ------------------------------------------------
            -- C2L_CMD_PH: передача команды
            -- ------------------------------------------------
            when C2L_CMD_PH =>

                if write_finish = '1' then
                    -- Команда отправлена.
                    -- Теперь нужно определить, требуются ли данные.
                    next_state <= C2L_WAIT_VALID;
                end if;


            -- ------------------------------------------------
            -- C2L_WAIT_VALID: ожидание данных после команды
            -- ------------------------------------------------
            when C2L_WAIT_VALID =>

                if cmd_cycle = x"0001" then
                    -- Команда рассчитана на один цикл.
                    -- После отправки команды завершаем обработку.
                    next_state <= C2L_FINISH;

                elsif data_wr_valid = '1' then
                    -- Доступно слово данных — начинаем запись.
                    next_state <= C2L_WRITE_DATA;
                end if;


            -- ------------------------------------------------
            -- C2L_WRITE_DATA: передача слова данных
            -- ------------------------------------------------
            when C2L_WRITE_DATA =>

                if write_finish = '1' then
                    -- Текущее слово данных отправлено.
                    -- Переходим к проверке количества циклов.
                    next_state <= C2L_WAIT_WR_VALID;
                end if;


            -- ------------------------------------------------
            -- C2L_WAIT_WR_VALID: ожидание следующей операции
            -- ------------------------------------------------
            when C2L_WAIT_WR_VALID =>

                if cycle_cnt = unsigned(cmd_cycle) then
                    -- Количество выполненных циклов достигло
                    -- заданного значения cmd_cycle.
                    next_state <= C2L_FINISH;

                elsif cmd_valid = '1' then
                    -- Поступила следующая команда.
                    next_state <= C2L_CMD_PH;

                elsif data_wr_valid = '1' then
                    -- Поступило следующее слово данных.
                    next_state <= C2L_WRITE_DATA;
                end if;


            -- ------------------------------------------------
            -- C2L_FINISH: завершение команды
            -- ------------------------------------------------
            when C2L_FINISH =>

                -- После одного такта возвращаемся к ожиданию.
                next_state <= C2L_IDLE;


            -- ------------------------------------------------
            -- Защитная ветка
            -- ------------------------------------------------
            when others =>
                next_state <= C2L_IDLE;

        end case;
    end process;


    -- ========================================================
    -- 10. Регистр состояния автомата
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            -- После сброса автомат ждет новую команду.
            state <= C2L_IDLE;

        elsif rising_edge(clk) then
            -- На каждом такте принимаем рассчитанное
            -- следующее состояние.
            state <= next_state;
        end if;
    end process;


    -- ========================================================
    -- 11. Управление направлением и содержимым шины data_lcd
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            data_lcd_oe  <= '0';
            data_lcd_out <= (others => '0');

        elsif rising_edge(clk) then

            case state is

                -- --------------------------------------------
                -- Передача команды
                -- --------------------------------------------
                when C2L_CMD_PH =>

                    -- Разрешаем управление внешней шиной.
                    data_lcd_oe <= '1';

                    -- Команда занимает младшие 8 бит шины.
                    -- Старшие 8 бит заполняются нулями.
                    data_lcd_out <= x"00" & cmd;


                -- --------------------------------------------
                -- Передача данных
                -- --------------------------------------------
                when C2L_WRITE_DATA =>

                    -- Разрешаем управление внешней шиной.
                    data_lcd_oe <= '1';

                    -- Выводим 16-битное слово данных.
                    data_lcd_out <= data_wr;


                -- --------------------------------------------
                -- Остальные состояния
                -- --------------------------------------------
                when others =>

                    -- Освобождаем внешнюю шину.
                    data_lcd_oe <= '0';

            end case;

        end if;
    end process;


    -- ========================================================
    -- 12. Формирование подтверждения записи ack_wr
    -- ========================================================

    ack_wr <= '1'
        when (state = C2L_WRITE_DATA) and
             (low_cnt = to_unsigned(W_LOW_END, low_cnt'length)) and
             (wrn = '0')
        else '0';

    -- ack_wr становится активным, когда:
    --   1. Автомат передает слово данных;
    --   2. low_cnt достиг W_LOW_END;
    --   3. Сигнал WR_N находится в активном низком состоянии.
    --
    -- Внешний модуль может использовать ack_wr как признак
    -- выполнения соответствующего этапа записи.


    -- ========================================================
    -- 13. Формирование признака завершения команды
    -- ========================================================

    cmd_finish <= '1' when state = C2L_FINISH else '0';

    -- cmd_finish активен, пока автомат находится в C2L_FINISH.
    -- Это не обязательно означает, что дисплей уже обновил
    -- физическое изображение: сигнал отражает состояние
    -- данного интерфейсного автомата.


    -- ========================================================
    -- 14. Формирование wrphase_finish
    -- ========================================================

    wrphase_finish <= '1'
        when (state = C2L_WRITE_DATA) and
             (high_cnt = to_unsigned(W_HIGH_END, high_cnt'length))
        else '0';

    -- Признак окончания временной фазы передачи данных.
    -- Активируется в состоянии C2L_WRITE_DATA,
    -- когда счетчик high_cnt достигает W_HIGH_END.


    -- ========================================================
    -- 15. Управление CS_N
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            csn <= '1';
            -- При сбросе LCD не выбран.

        elsif rising_edge(clk) then

            if state = C2L_CMD_PH then
                -- Активируем LCD перед передачей команды.
                csn <= '0';

            elsif state = C2L_FINISH then
                -- После завершения команды снимаем выбор LCD.
                csn <= '1';
            end if;

        end if;
    end process;


    -- ========================================================
    -- 16. Управление сигналом выбора команды/данных
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            data_cmdn <= '1';
            -- Начальное значение — режим данных.

        elsif rising_edge(clk) then

            if state = C2L_CMD_PH then
                -- Во время передачи команды выбираем режим команды.
                data_cmdn <= '0';

            else
                -- Во всех остальных состояниях выбираем режим данных.
                data_cmdn <= '1';
            end if;

        end if;
    end process;


    -- ========================================================
    -- 17. Управление сигналом WR_N
    -- ========================================================

    process(clk, rst_n)
    begin
        if rst_n = '0' then
            wrn <= '1';
            -- При сбросе запись не активна.

        elsif rising_edge(clk) then

            if (state = C2L_CMD_PH) or
               (state = C2L_WRITE_DATA) then

                -- Во время передачи команда/данные записываются
                -- путем формирования активного низкого уровня WR_N.
                if low_cnt = to_unsigned(W_LOW_END, low_cnt'length) then
                    wrn <= '1';
                    -- Завершаем активную часть импульса записи.
                else
                    wrn <= '0';
                    -- Активная часть импульса записи.
                end if;

            else
                -- Вне передачи WR_N неактивен.
                wrn <= '1';
            end if;

        end if;
    end process;

end architecture rtl;
